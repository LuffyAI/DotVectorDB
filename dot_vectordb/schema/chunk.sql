/* 
 **REQUIRED**
 This table stores the embedding models used to generate vector representations of text chunks. Each embedding model is associated with a unique model_id and a model_name that describes the model. The model_metadata column allows the user to store additional information about the embedding model, such as its architecture, training data, or hyperparameters.
*/
CREATE TABLE IF NOT EXISTS embedding_model (
    id TEXT NOT NULL,
    name TEXT NOT NULL,
    description JSON,
    PRIMARY KEY (id)
);

/* 
 **REQUIRED**
 This table stores the original source documents that are ingested into the system. Each source document is associated with a unique source_id, and the content of the document is stored in the content column. The source metadata allows the user to add comments and additional information
 about the source, such as authors, website, or citations. The created_at column records the timestamp when the source document was ingested into the system.
*/
CREATE TABLE IF NOT EXISTS source (
    id TEXT NOT NULL,
    name TEXT NOT NULL,
    description JSON,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    num_chunks INT DEFAULT 0,
    num_entities INT DEFAULT 0,
    num_relations INT DEFAULT 0,
    raw_corpus_tokens INT DEFAULT 0,
    entity_construct_tokens INT DEFAULT 0,
    entity_deduplication_tokens INT DEFAULT 0,
    relation_construct_tokens INT DEFAULT 0,
    PRIMARY KEY (id)
);

/**REQUIRED**
 This table chunks each source document into smaller pieces and stores the content of each chunk, along with its corresponding embedding and model information. Each chunk is associated with a unique chunk_id and a source_id that references the original source document. The content column contains the text of the chunk, while the embedding column stores the vector representation of the chunk generated by the embedding model. The created_at column records the timestamp when each chunk was created. The foreign key constraint ensures that each chunk is linked to a valid source document, and if a source document is deleted, all associated chunks will also be deleted (ON DELETE CASCADE).
*/
CREATE TABLE IF NOT EXISTS chunk (
    chunk_id INTEGER NOT NULL,
    source_id TEXT NOT NULL,
    content TEXT NOT NULL,
    embedding_model_id TEXT NOT NULL,
    is_embedded BOOLEAN DEFAULT FALSE,
    are_entities_extracted BOOLEAN DEFAULT FALSE,
    are_relations_extracted BOOLEAN DEFAULT FALSE,
    PRIMARY KEY (chunk_id),
    FOREIGN KEY (source_id) REFERENCES source(id) ON DELETE CASCADE,
    FOREIGN KEY (embedding_model_id) REFERENCES embedding_model(id) ON DELETE CASCADE
);

/**Trigger**
After a new chunk is inserted into the chunk table, this trigger increments the num_chunks field in the corresponding source record. This ensures that the source record accurately reflects the number of chunks associated with it.
*/
CREATE TRIGGER IF NOT EXISTS increment_source_num_chunks
AFTER INSERT ON chunk
BEGIN
    UPDATE source
    SET num_chunks = num_chunks + 1
    WHERE id = NEW.source_id;
END;

/**Trigger**
After a chunk is deleted from the chunk table, this trigger decrements the num_chunks field in the corresponding source record. This ensures that the source record accurately reflects the number of chunks associated with it.
*/
CREATE TRIGGER IF NOT EXISTS decrement_source_num_chunks
AFTER DELETE ON chunk
BEGIN
    UPDATE source
    SET num_chunks = MAX(num_chunks - 1, 0)
    WHERE id = OLD.source_id;
END;